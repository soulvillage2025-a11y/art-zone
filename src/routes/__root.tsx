function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="es">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function SiteHeader() {
  const [signedIn, setSignedIn] = useState(false);

  useEffect(() => {
    let active = true;
    const localRole = typeof window !== "undefined" ? localStorage.getItem("telopinto_role") : null;
    if (localRole) {
      setSignedIn(true);
    }
    supabase.auth.getUser().then(({ data }) => {
      if (active) setSignedIn(Boolean(data.user) || Boolean(localStorage.getItem("telopinto_role")));
    });
    const { data: sub } = supabase.auth.onAuthStateChange((_event, session) => {
      setSignedIn(Boolean(session?.user) || Boolean(localStorage.getItem("telopinto_role")));
    });
    return () => {
      active = false;
      sub.subscription.unsubscribe();
    };
  }, []);

  return (
    <header className="no-print sticky top-0 z-40 border-b border-border bg-background/85 backdrop-blur">
      <div className="mx-auto flex h-16 max-w-6xl items-center justify-between px-5">
        <Link to="/" className="font-display text-xl tracking-tight">
          TeLoPinto<span className="text-primary">.</span>
        </Link>
        <nav className="flex items-center gap-1 text-sm">
          <Link
            to="/catalogo"
            className="rounded-md px-3 py-2 text-muted-foreground transition-colors hover:bg-secondary hover:text-foreground"
            activeProps={{ className: "rounded-md px-3 py-2 text-foreground bg-secondary" }}
          >
            Catálogo
          </Link>
          {signedIn ? (
            <Link
              to="/dashboard"
              className="rounded-md bg-primary px-3 py-2 font-medium text-primary-foreground transition-colors hover:bg-primary/90"
            >
              Panel del taller
            </Link>
          ) : (
            <Link
              to="/auth"
              className="rounded-md border border-border px-3 py-2 transition-colors hover:bg-secondary"
            >
              Acceso taller
            </Link>
          )}
        </nav>
      </div>
    </header>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <SiteHeader />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
